// coercion, loose equality (==) vs strict equality (===) in JavaScript
console.log('"5" + 3 =', "5" + 3); 
console.log('"5" - 3 =', "5" - 3); 
console.log(NaN === NaN); 
console.log('typeof NaN =', typeof NaN);
console.log('5 == "5" =', 5 == "5"); 
console.log('5 === "5" =', 5 === "5"); 
console.log('false == 0 =', false == 0); 
console.log('false === 0 =', false === 0); 
console.log('"" == 0 =', "" == 0); 
console.log('"" === 0 =', "" === 0); 
